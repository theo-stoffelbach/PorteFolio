// Sprites en lignes de caractères. Pour l'écran LCD : « 0 » clair → « 3 » sombre,
// « . » transparent. Pour les petites icônes d'étiquette : « # » = encre.

export type Sprite = readonly string[];

// Miroir horizontal (pour faire marcher Théo vers la gauche).
export function mirror(rows: Sprite): Sprite {
  return rows.map((r) => r.split('').reverse().join(''));
}

