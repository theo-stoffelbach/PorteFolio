// Caractères typographiques ramenés à ce que les polices savent dessiner.
const ALIASES: Readonly<Record<string, string>> = {
  '’': "'",
  '‘': "'",
  'ʼ': "'",
  '´': "'",
  '`': "'",
  '“': '"',
  '”': '"',
  '„': '"',
  '–': '-',
  '—': '-',
  '‑': '-',
  '−': '-',
  ' ': ' ',
  ' ': ' ',
  ' ': ' ',
  '\t': ' ',
  '×': 'x',
  '✉': '@',
};

export function normalizeText(text: string): string {
  let out = '';
  for (const ch of text) out += ALIASES[ch] ?? ch;
  return out;
}

const QUESTION = '?';

// Glyphe d'un caractère : direct, sinon sa lettre de base sans accent, sinon « ? ».
// Un caractère inconnu ne disparaît donc jamais en silence.
export function glyphFor(f: BitmapFont, ch: string): Glyph {
  const direct = f.glyphs.get(ch);
  if (direct) return direct;
  const base = ch.normalize('NFD').charAt(0);
  if (base && base !== ch) {
    const g = f.glyphs.get(f.upper ? base.toUpperCase() : base);
    if (g) return g;
  }
  return f.glyphs.get(QUESTION) as Glyph;
}

function prepare(f: BitmapFont, text: string): string {
  const t = normalizeText(text);
  return f.upper ? t.toUpperCase() : t;
}

// Nombre de pixels dont les accents du texte montent au-dessus des capitales
// (pour laisser la place nécessaire dans un bandeau ou une enseigne).
export function accentRise(f: BitmapFont, text: string): number {
  let rise = 0;
  for (const ch of prepare(f, text)) {
    const dy = glyphFor(f, ch).dy ?? 0;
    if (dy < 0) rise = Math.max(rise, -dy);
  }
  return rise;
}

export function textWidth(f: BitmapFont, text: string): number {
  let w = 0;
  for (const ch of prepare(f, text)) w += ch === ' ' ? f.space + 1 : glyphFor(f, ch).w + 1;
  return Math.max(0, w - 1);
}

// Dessine le texte et renvoie sa largeur ; `k` agrandit chaque pixel en bloc k×k.
export function drawText(
  s: Surface,
  f: BitmapFont,
  text: string,
  x: number,
  y: number,
  c: Color,
  k = 1
): number {
  let cx = x;
  const dot = (gx: number, gy: number) => {
    if (k === 1) {
      px(s, gx, gy, c);
      return;
    }
    for (let j = 0; j < k; j++) for (let i = 0; i < k; i++) px(s, gx + i, gy + j, c);
  };
  for (const ch of prepare(f, text)) {
    if (ch === ' ') {
      cx += (f.space + 1) * k;
      continue;
    }
    const g = glyphFor(f, ch);
    for (let j = 0; j < g.rows.length; j++) {
      const r = g.rows[j];
      for (let i = 0; i < r.length; i++) if (r[i] === '#') dot(cx + i * k, y + j * k);
    }
    if (g.acc) {
      const dy = g.dy ?? 0;
      for (let j = 0; j < g.acc.length; j++) {
        const r = g.acc[j];
        for (let i = 0; i < r.length; i++) if (r[i] === '#') dot(cx + i * k, y + (dy + j) * k);
      }
    }
    cx += (g.w + 1) * k;
  }
  return Math.max(0, cx - x - k);
}

export function drawTextCentered(
  s: Surface,
  f: BitmapFont,
  text: string,
  cx: number,
  y: number,
  c: Color,
  k = 1
): number {
  const w = textWidth(f, text) * k;
  return drawText(s, f, text, cx - (w >> 1), y, c, k);
}

// Coupe un mot trop long pour la largeur disponible.
function splitWord(f: BitmapFont, word: string, maxWidth: number): string[] {
  const parts: string[] = [];
  let cur = '';
  for (const ch of word) {
    if (cur && textWidth(f, cur + ch) > maxWidth) {
      parts.push(cur);
      cur = ch;
    } else cur += ch;
  }
  if (cur) parts.push(cur);
  return parts;
}

// Retour à la ligne au mot près ; « \n » force une nouvelle ligne.
export function wrapText(f: BitmapFont, text: string, maxWidth: number): string[] {
  const lines: string[] = [];
  for (const paragraph of normalizeText(text).split('\n')) {
    let cur = '';
    for (const raw of paragraph.split(' ')) {
      if (!raw) continue;
      const words = textWidth(f, raw) > maxWidth ? splitWord(f, raw, maxWidth) : [raw];
      for (const word of words) {
        const next = cur ? `${cur} ${word}` : word;
        if (cur && textWidth(f, next) > maxWidth) {
          lines.push(cur);
          cur = word;
        } else cur = next;
      }
    }
    lines.push(cur);
  }
  return lines;
}

// Tronque une ligne avec « … » pour tenir dans la largeur.
export function fitText(f: BitmapFont, text: string, maxWidth: number): string {
  if (textWidth(f, text) <= maxWidth) return text;
  let cut = normalizeText(text);
  while (cut && textWidth(f, `${cut}…`) > maxWidth) cut = cut.slice(0, -1);
  return `${cut.trimEnd()}…`;
}
