// Polices bitmap maison, portées de la maquette puis complétées pour le français.
// Chaque glyphe est une suite de lignes séparées par « | » ; « # » = pixel allumé.
// Les accents sont des calques posés au-dessus (ou au-dessous) d'une lettre de base.

export interface Glyph {
  w: number;
  rows: string[];
  acc?: string[];
  dy?: number;
}

export interface BitmapFont {
  glyphs: Map<string, Glyph>;
  space: number;
  // Hauteur des capitales et pas de ligne conseillé (accents compris).
  height: number;
  lineHeight: number;
  // Police en capitales seulement : le texte est mis en majuscules avant le dessin.
  upper: boolean;
}

type AccentDef = [base: string, rows: string[], dy: number];

function buildFont(
  def: Record<string, string>,
  acc: Record<string, AccentDef>,
  o: { space: number; height: number; lineHeight: number; upper: boolean }
): BitmapFont {
  const glyphs = new Map<string, Glyph>();
  for (const key of Object.keys(def)) {
    const rows = def[key].split('|');
    glyphs.set(key, { w: Math.max(...rows.map((r) => r.length)), rows });
  }
  for (const key of Object.keys(acc)) {
    const [baseKey, rows, dy] = acc[key];
    const base = glyphs.get(baseKey);
    if (!base) throw new Error(`Police bitmap : lettre de base « ${baseKey} » absente pour « ${key} »`);
    glyphs.set(key, { w: base.w, rows: base.rows, acc: rows, dy });
  }
  return { glyphs, space: o.space, height: o.height, lineHeight: o.lineHeight, upper: o.upper };
}

